export function getObjectDef(type: ObjectType): ObjectTypeDef {
  return OBJECT_TYPES[type];
}

export function findParamDef(type: ObjectType, id: string): ParamDef | undefined {
  return OBJECT_TYPES[type].params.find((p) => p.id === id);
}
