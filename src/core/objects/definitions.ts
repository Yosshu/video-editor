export interface ObjectTypeDef {
  type: ObjectType;
  label: string;
  /** タイムライン上の色 */
  color: string;
  /** 映像を持つか */
  visual: boolean;
  /** 音声を持つか */
  audio: boolean;
  /** 参照する素材の種類 */
  assetKind?: AssetKind;
  /** 制御オブジェクト（それ自体は描かれず、他のレイヤーに作用する） */
  control?: boolean;
  /** エフェクトを追加できるか */
  effects?: boolean;
  params: ParamDef[];
}

